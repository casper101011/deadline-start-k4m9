const ol = items => `<ol>${items.map(i => `<li>${i}</li>`).join('')}</ol>`;
const BOX_META = {
  example: ['lightbulb', 'Пример'],
  mistake: ['alert', 'Ошибка'],
  tip: ['zap', 'Важно'],
  template: ['copy', 'Шаблон'],
  good: ['checkCircle', 'Так правильно'],
};
const box = (type, html, title) => {
  const [ic, def] = BOX_META[type] || BOX_META.example;
  return `<div class="box ${type}"><div class="box-title">${icon(ic, 'icon-sm')}${title || def}</div>${html}</div>`;
};
const cmp = (bad, good) => `<div class="compare"><div class="bad"><small>Слабо</small><p>${bad}</p></div><div class="good"><small>Сильно</small><p>${good}</p></div></div>`;
const h2 = (id, n, t) => `<h2 id="${id}">${n ? `<span class="step-n">Шаг ${n}</span>` : ''}${t}</h2>`;
const flow = steps => `<div class="funnel-steps">${steps.map(s => `<span>${s}</span>`).join(icon('arrowRight'))}</div>`;
let __nt = 0;
const niches = (tabs, note = 'Цифры в примерах условные — подставляйте данные своего клиента.') => {
  const id = 'nt' + (++__nt);
  return `<div class="niche-tabs" data-nt="${id}">
    <div class="nt-head">${tabs.map((t, i) => `<button type="button" class="${i ? '' : 'on'}" data-i="${i}">${t[0]}</button>`).join('')}</div>
    <div class="nt-body">${tabs.map((t, i) => `<div class="${i ? '' : 'on'}">${box('example', t[1], 'Пример: ' + t[0].toLowerCase())}</div>`).join('')}</div>
    ${note ? `<p style="font-size:13px;color:var(--muted);margin:8px 0 0">${note}</p>` : ''}
  </div>`;
};
const scene = (t, what, shot) => `<div class="scene"><div class="t">${t}</div><div><div class="what">${what}</div><div class="shot">${shot}</div></div></div>`;

