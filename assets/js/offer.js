// Запрос к нейросети через «мостик» (если он подключён в config.js)
async function askAI(prompt) {
  const url = (window.DL_CONFIG || {}).AI_ENDPOINT;
  const r = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ prompt }) });
  if (!r.ok) throw new Error('Нейросеть не ответила (' + r.status + '). Попробуйте ещё раз.');
  const j = await r.json();
  if (!j.text) throw new Error(j.error || 'Пустой ответ нейросети.');
  return j.text;
}

